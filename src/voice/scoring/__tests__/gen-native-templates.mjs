// Generates src/voice/scoring/nativeTemplates.ts from the calibrated native corpus.
//   npx tsx src/voice/scoring/__tests__/gen-native-templates.mjs [framesDir]
import fs from 'node:fs'
import path from 'node:path'
import { scoreTone } from '../index.ts'
import { rangeFromCalibration } from '../../engine/range.ts'
const DIR = process.argv[2] ?? '/tmp/claude-1000/-mnt-sda1-hieubm-Hibu-Hanzi/88cd1e47-1511-4ce0-b36f-1dc12fc21aa0/scratchpad/tone/frames'
const K = 13
const acc = { 1: [], 2: [], 3: [], 4: [] }
const per = {} // per-speaker rows, for the band
for (const sp of fs.readdirSync(DIR)) {
  const d = path.join(DIR, sp); const L = (n) => JSON.parse(fs.readFileSync(path.join(d, n + '.json'), 'utf8'))
  const range = rangeFromCalibration(['ma1', 'ma2', 'ma3', 'ma4'].map(L))
  for (const f of fs.readdirSync(d)) {
    const m = f.match(/^([a-z]+)([1-4])\.json$/); if (!m) continue
    const t = +m[2]; const r = scoreTone(L(m[1] + m[2]), t, range)
    if (r.detected !== t) continue
    const y = r.contour.map((p) => p.y), n = y.length
    const row = (Array.from({ length: K }, (_, i) => { const x = (i / (K - 1)) * (n - 1), a = Math.floor(x), b = Math.min(n - 1, a + 1); return y[a] + (y[b] - y[a]) * (x - a) }))
    acc[t].push(row); ((per[sp] ??= { 1: [], 2: [], 3: [], 4: [] })[t]).push(row)
  }
}
const q = (v, p) => { const s = [...v].sort((a, b) => a - b); const i = (s.length - 1) * p, lo = Math.floor(i); return s[lo] + (s[Math.ceil(i)] - s[lo]) * (i - lo) }
const r2 = (v) => Math.round(v * 100) / 100
const out = { mean: {}, lo: {}, hi: {}, n: {} }
for (const t of [1, 2, 3, 4]) {
  const rows = acc[t]; out.n[t] = rows.length
  out.mean[t] = []; out.lo[t] = []; out.hi[t] = []
  for (let i = 0; i < K; i++) { const col = rows.map((r) => r[i]); const x = r2(i / (K - 1)); out.mean[t].push({ x, y: r2(col.reduce((a, b) => a + b, 0) / col.length) }); const sps = Object.values(per).map((p) => p[t].map((r) => r[i])); out.lo[t].push({ x, y: r2(Math.min(...sps.map((c) => q(c, 0.05)))) }); out.hi[t].push({ x, y: r2(Math.max(...sps.map((c) => q(c, 0.95)))) }) }
}
const fmt = (o) => '{\n' + [1, 2, 3, 4].map((t) => `  ${t}: [${o[t].map((p) => `{ x: ${p.x}, y: ${p.y} }`).join(', ')}],`).join('\n') + '\n}'
fs.writeFileSync(new URL('../nativeTemplates.ts', import.meta.url), `// GENERATED by scoring/__tests__/gen-native-templates.mjs — do not edit by hand.
// Derived from ${Object.values(out.n).reduce((a, b) => a + b)} correctly-detected native tokens (2 female voices, jsd + allset,
// ~205 syllables × tones 1–4, tones ${JSON.stringify(out.n)}), each speaker calibrated from her own mā/má/mǎ/mà with
// rangeFromCalibration(); contours from scoreTone().contour (display Chao, 0..1 voiced time), resampled to ${K} points.
// MEAN = per-point mean; BAND = union over speakers of each speaker's 5th..95th percentile (natural variation, used as the UI lane).
import type { ContourPoint } from '../types'

export const NATIVE_TEMPLATES: Record<1 | 2 | 3 | 4, ContourPoint[]> = ${fmt(out.mean)}

export const NATIVE_BAND: Record<1 | 2 | 3 | 4, { lo: ContourPoint[]; hi: ContourPoint[] }> = {
${[1, 2, 3, 4].map((t) => `  ${t}: {\n    lo: [${out.lo[t].map((p) => `{ x: ${p.x}, y: ${p.y} }`).join(', ')}],\n    hi: [${out.hi[t].map((p) => `{ x: ${p.x}, y: ${p.y} }`).join(', ')}],\n  },`).join('\n')}
}

/** Linear interpolation on a template (x in 0..1). */
export function contourAt(pts: ContourPoint[], x: number): number {
  if (x <= pts[0].x) return pts[0].y
  for (let i = 1; i < pts.length; i++) if (x <= pts[i].x) { const a = pts[i - 1], b = pts[i]; return a.y + ((b.y - a.y) * (x - a.x)) / (b.x - a.x || 1) }
  return pts[pts.length - 1].y
}
`)
